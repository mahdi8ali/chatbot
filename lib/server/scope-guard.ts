// قوائم الكلمات المفتاحية (تُطبَّع مرّة واحدة عند التحميل لضمان اتساق المطابقة)
// ---------------------------------------------------------------------------

/** أسماء الأشهر الهجرية (تشمل صيغاً إملائية بديلة). */
const HIJRI_MONTHS: string[] = [
  "محرم",
  "صفر",
  "ربيع الاول",
  "ربيع الثاني",
  "جمادى الاولى",
  "جمادى الاخرة",
  "جمادى الآخرة",
  "رجب",
  "شعبان",
  "رمضان",
  "شوال",
  "ذو القعدة",
  "ذي القعدة",
  "ذو الحجة",
  "ذي الحجة",
].map(normalizeArabic)

/** أفعال/عبارات تدلّ على نيّة تحويل التقويم (هجري ↔ ميلادي). */
const CONVERSION_PHRASES: string[] = [
  "حول",
  "حوّل",
  "يوافق",
  "يصادف",
  "كم يصادف",
  "بالميلادي",
  "بالهجري",
  "الى ميلادي",
  "الى الميلادي",
  "ما يقابله",
  "ما يوافق",
].map(normalizeArabic)

/** أدوات الاستفهام الزمنية (تدلّ على سؤال عن توقيت/تاريخ). */
const TIME_INTERROGATIVES: string[] = [
  "متى",
  "اي يوم",
  "باي تاريخ",
  "في اي يوم",
  "ما تاريخ",
  "ما هو تاريخ",
  "تاريخ",
].map(normalizeArabic)

/** أسماء المناسبات الدينية التي يخرج توقيتها عن النطاق. */
const OCCASIONS: string[] = [
  "الاربعين",
  "عاشوراء",
  "الغدير",
  "عيد الغدير",
  "المولد",
  "ليلة القدر",
  "الاستشهاد",
  "استشهاد",
  "الوفاة",
  "وفاة",
  "النصف من شعبان",
  "عرفة",
  "عيد الفطر",
  "عيد الاضحى",
].map(normalizeArabic)

/**
 * أسماء «المحتوى»: وجود أيٍّ منها يعني أن المستخدم يريد محتوى العتبة
 * (خبر/خدمة/فعالية/مشروع...) لا تاريخاً أو توقيتاً — فيُفرض بقاؤه داخل النطاق.
 * (Requirement 3.5: «أخبار/خدمات/فعاليات العتبة في الأربعين» تبقى داخل النطاق.)
 */
const CONTENT_NOUNS: string[] = [
  "أخبار",
  "خبر",
  "خدمات",
  "خدمة",
  "فعاليات",
  "فعالية",
  "برنامج",
  "برامج",
  "مشاريع",
  "مشروع",
  "زيارة الخدمية",
  "موكب",
  "مواكب",
  "استعدادات",
  "تغطية",
  "صور",
  "فيديو",
  "بث",
].map(normalizeArabic)

/**
 * تعبير سنة هجرية مقرونة بعلامة هجرية، مثل «1448 هـ» أو «1448 هجرية».
 * بعد التطبيع تصبح «هـ» → «ه» و«هجرية» → «هجريه»، لذا نطابق العلامات الثلاث.
 * رقم من 3 إلى 4 خانات متبوعاً (بمسافة اختيارية) بعلامة هجرية عند حدّ كلمة.
 */
const HIJRI_YEAR_REGEX = /\d{3,4}\s*(هجريه|هجري|ه)(\s|$)/

// ---------------------------------------------------------------------------
// الدالة العامة: classifyScope
// ---------------------------------------------------------------------------

/**
 * تُصنّف رسالة المستخدم. الترتيب مقصود:
 *   1) التطبيع.
 *   2) تجاوز المحتوى (Content override) أولاً → داخل النطاق فوراً.
 *   3) تحويل هجري (شهر هجري + سنة/عبارة تحويل).
 *   4) توقيت مناسبة (أداة استفهام زمنية + اسم مناسبة).
 *   5) الافتراضي المحافظ: داخل النطاق.
 */
export function classifyScope(userMessage: string): ScopeResult {
  // مدخل فارغ/غير نصّي → داخل النطاق (محافظ).
  if (!userMessage || typeof userMessage !== "string") {
    return { inScope: true }
  }

  const norm = normalizeArabic(userMessage)
  if (!norm) {
    return { inScope: true }
  }

  // (2) تجاوز المحتوى — يُفحص أولاً: أي اسم محتوى يعني أن السؤال عن محتوى
  // العتبة (لا عن تاريخ/توقيت) فيبقى داخل النطاق حتى مع وجود اسم مناسبة.
  for (const noun of CONTENT_NOUNS) {
    if (hasPhrase(norm, noun)) {
      return { inScope: true }
    }
  }

  // (3) تحويل التواريخ الهجرية: يتطلب اسم شهر هجري + (سنة هجرية أو عبارة تحويل).
  const hasHijriMonth = HIJRI_MONTHS.some((m) => hasPhrase(norm, m))
  if (hasHijriMonth) {
    const hasHijriYear = HIJRI_YEAR_REGEX.test(norm)
    const hasConversionPhrase = CONVERSION_PHRASES.some((p) => hasPhrase(norm, p))
    if (hasHijriYear || hasConversionPhrase) {
      return {
        inScope: false,
        category: "hijri_conversion",
        reason:
          "طلب تحويل تاريخ هجري (اسم شهر هجري مقرون بسنة هجرية أو عبارة تحويل) — خارج نطاق مساعد العتبة.",
      }
    }
  }

  // (4) توقيت المناسبات الدينية: أداة استفهام زمنية + اسم مناسبة.
  const hasTimeInterrogative = TIME_INTERROGATIVES.some((t) => hasPhrase(norm, t))
  if (hasTimeInterrogative) {
    const hasOccasion = OCCASIONS.some((o) => hasPhrase(norm, o))
    if (hasOccasion) {
      return {
        inScope: false,
        category: "occasion_timing",
        reason:
          "سؤال عن توقيت مناسبة دينية (أداة استفهام زمنية مقرونة باسم مناسبة) — يُوجَّه للتقويم لا لمعرفة عامة.",
      }
    }
  }

  // (5) الافتراضي المحافظ: عند عدم وجود مطابقة واضحة نبقى داخل النطاق.
  // لا نحاول كشف «المعلومات العامة» حتمياً (فضفاض جداً) — يُترك لشبكة الأمان
  // tool_choice:"auto" والموجّه.
  return { inScope: true }
}
