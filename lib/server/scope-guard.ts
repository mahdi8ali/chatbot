/**
 * scope-guard.ts — حارس النطاق الحتمي (Deterministic Scope Guard)
 *
 * وحدة نقية حتمية (PURE / DETERMINISTIC): بلا أي I/O أو استدعاء نموذج لغوي.
 * تُصنّف رسالة المستخدم إلى «داخل النطاق» أو «خارج النطاق» قبل أن يدخل الطلب
 * تدفّق الأدوات، لتقصير المسار على الأسئلة التي لا تخص العتبة العباسية المقدسة
 * (تحويل التواريخ الهجرية، وتوقيت المناسبات الدينية).
 *
 * فلسفة التصميم: **دقة عالية ومحافظة** (HIGH-PRECISION, CONSERVATIVE).
 * عند أي شكّ أو عدم مطابقة واضحة نُرجع { inScope: true } لتفادي أي انحدار
 * (regression) في الأسئلة المشروعة داخل النطاق.
 *
 * نمط التطبيع العربي مأخوذ من `normalizeArabic` في `faq.ts` مع توسعة بسيطة
 * (تجريد التشكيل والتطويل وتوحيد الأرقام العربية) لضمان اتساق المطابقة.
 *
 * _Requirements: 2.1, 2.3, 2.4, 2.5, 2.6, 3.5_
 */

/** فئات الأسئلة خارج النطاق التي يكتشفها الحارس الحتمي. */
export type OutOfScopeCategory = "hijri_conversion" | "occasion_timing"

/** نتيجة التصنيف: داخل النطاق أم خارجه، ومع الفئة والسبب عند الخروج. */
export interface ScopeResult {
  inScope: boolean
  category?: OutOfScopeCategory
  reason?: string
}

/**
 * تطبيع النص العربي لأغراض المطابقة الحتمية:
 * - توحيد الأرقام العربية (٠-٩) إلى اللاتينية (0-9) كي تعمل `\d`.
 * - تجريد التشكيل (الفتحة/الضمة/الكسرة/الشدة/السكون...) والألف الخنجرية والتطويل (ـ).
 * - توحيد الهمزات والألف: [أإآا] → ا، ء تُحذف، ؤ → و، ئ → ي.
 * - التاء المربوطة ة → ه، والألف المقصورة ى → ي.
 * - استبدال علامات الترقيم بمسافة لتمكين مطابقة حدود الكلمات.
 * - دمج المسافات وقصّها وتحويل الأحرف اللاتينية لحالة صغيرة.
 *
 * مطابق في الروح لـ `normalizeArabic` في `faq.ts` (لم نُدرج قاعدتَي
 * «و في نهاية الكلمة → ي» و«فاضل → فضل» لأنهما خاصّتان بأسئلة FAQ).
 */
function normalizeArabic(text: string): string {
  return text
    // توحيد الأرقام العربية-الهندية إلى اللاتينية
    .replace(/[٠-٩]/g, (d) => String("٠١٢٣٤٥٦٧٨٩".indexOf(d)))
    // تجريد التشكيل (U+064B..U+0652) والألف الخنجرية (U+0670)
    .replace(/[\u064B-\u0652\u0670]/g, "")
    // تجريد التطويل (ـ) — يحوّل مثلاً «هـ» إلى «ه»
    .replace(/\u0640/g, "")
    // استبدال علامات الترقيم العربية بمسافة (فاصلة ، فاصلة منقوطة ؛ علامة استفهام ؟
    // ونحوها) — هذه الرموز تقع داخل نطاق U+0600..U+06FF فلا يلتقطها التجريد العام أدناه.
    .replace(/[\u060C\u060D\u061B\u061E\u061F\u066A-\u066D\u06D4]/g, " ")
    // توحيد الهمزات والألف
    .replace(/[أإآا]/g, "ا")
    .replace(/ء/g, "")
    .replace(/ؤ/g, "و")
    .replace(/ئ/g, "ي")
    // التاء المربوطة والألف المقصورة
    .replace(/ة/g, "ه")
    .replace(/ى/g, "ي")
    // استبدال أي رمز غير حرف عربي/لاتيني/رقم/مسافة بمسافة (ترقيم عربي وإنجليزي)
    .replace(/[^\w\u0600-\u06FF\s]/g, " ")
    // دمج المسافات
    .replace(/\s+/g, " ")
    .trim()
    .toLowerCase()
}

/**
 * مطابقة عبارة كـ«رمز مستقل» (standalone token/phrase) على النص المُطبَّع.
 * نستخدم حدود مسافة/بداية/نهاية بدل `\b` لأن `\b` في JS مبني على أحرف ASCII
 * ولا يعمل بشكل صحيح مع الأحرف العربية. هذا يمنع الإفراط في المطابقة
 * (مثال: «صفر» الشهر يجب ألا يُطابق داخل كلمة أخرى).
 *
 * ملاحظة: النص المُطبَّع فُصلت رموزه بمسافات، لذا تعمل هذه الحدود لكلمة واحدة
 * أو لعبارة متعددة الكلمات على حدّ سواء.
 */
function hasPhrase(normText: string, normPhrase: string): boolean {
  if (!normPhrase) return false
  const escaped = normPhrase.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")
  const regex = new RegExp(`(^|\\s)${escaped}(\\s|$)`)
  return regex.test(normText)
}

