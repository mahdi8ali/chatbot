/**
 * مجاملات **لا لبس فيها**: تحية أو شكر أو وداع صريح. آمنة في أي موضع من المحادثة.
 */
const SMALLTALK_PHRASES: string[] = [
  "السلام عليكم", "سلام عليكم", "وعليكم السلام", "مرحبا", "مرحبتين", "اهلا",
  "اهلا وسهلا", "هلا", "صباح الخير", "مساء الخير", "تحياتي",
  "شكرا", "شكرا لك", "شكرا جزيلا", "مشكور", "ممنون", "يعطيك العافيه",
  "بارك الله فيك", "جزاك الله خيرا", "احسنت",
  "الله يحفظك", "في امان الله", "مع السلامه", "الى اللقاء", "وداعا",
].map(normalizeArabic)

/**
 * ⚠️ موافقات **غامضة** — مجاملة في بداية المحادثة، لكنها «نعم» في وسطها.
 *
 * في العامية العراقية، حين يسأل البوت «هل تريد تفاصيل أعمق؟» فيردّ المستخدم
 * «تمام» أو «اوكي» أو «طيب»، فهو يوافق لا يجامل. اعتبارها مجاملة يقصر المسار
 * ويردّ بترحيب عام فيضيع طلب المستخدم — وهو انحدار حقيقي رصده اختبار التسلسلية.
 *
 * لذا: تُعدّ مجاملة **فقط** إذا لم يسبقها ردّ من المساعد في المحادثة.
 */
const AMBIGUOUS_ACKS: string[] = [
  "تمام", "طيب", "اوكي", "ok", "ممتاز", "زين", "حسنا", "ماشي", "عاشت ايدك",
].map(normalizeArabic)

/** أقصى عدد كلمات تُعدّ عنده الرسالة مجاملة خالصة (تحفّظاً). */
const SMALLTALK_MAX_WORDS = 4

/**
 * هل الرسالة **مجاملة خالصة** لا سؤال فيها؟
 *
 * الغرض: `tool_choice: "required"` في التكرار الأول يُجبر استدعاء أداة لكل رسالة،
 * فتمرّ «شكراً» و«مرحبا» ببحث كامل في القاعدة واستدعاء نموذج إضافي — كلفة وزمن
 * وجواب غريب على تحية. وهذا يناقض الموجّه نفسه الذي يطلب عدم البحث للرسائل
 * القصيرة الغامضة.
 *
 * محافظ جداً (نفس فلسفة classifyScope): يشترط أن تكون الرسالة **قصيرة** وأن
 * تتكوّن **حصراً** من عبارات مجاملة، وأن تخلو من أي أداة استفهام أو علامة سؤال.
 * أي شكّ ⇒ false، فتسلك الرسالة المسار الطبيعي.
 */
export function isSmallTalk(
  userMessage: string,
  opts?: { hasPriorAssistantTurn?: boolean }
): boolean {
  if (!userMessage || typeof userMessage !== "string") return false

  // علامة استفهام صريحة ⇒ سؤال لا مجاملة (تُفحص قبل التطبيع الذي يزيلها)
  if (/[?؟]/.test(userMessage)) return false

  const norm = normalizeArabic(userMessage)
  if (!norm) return false

  const words = norm.split(/\s+/).filter(Boolean)
  if (words.length === 0 || words.length > SMALLTALK_MAX_WORDS) return false

  // أي أداة استفهام ⇒ ليست مجاملة
  const INTERROGATIVES = ["من", "ما", "متى", "اين", "كيف", "كم", "هل", "لماذا", "ماذا", "اي"]
  if (words.some((w) => INTERROGATIVES.includes(w))) return false

  // الموافقات الغامضة تُعدّ مجاملة فقط في بداية المحادثة؛ وسطها هي «نعم».
  const vocabulary = opts?.hasPriorAssistantTurn
    ? SMALLTALK_PHRASES
    : [...SMALLTALK_PHRASES, ...AMBIGUOUS_ACKS]

  // نزيل عبارات المجاملة تباعاً (الأطول أولاً) — إن لم يبقَ شيء فهي مجاملة خالصة
  let rest = ` ${norm} `
  for (const p of [...vocabulary].sort((a, b) => b.length - a.length)) {
    rest = rest.split(` ${p} `).join(" ")
  }
  // كلمات وصل مسموح بقاؤها
  for (const filler of ["و", "يا", "استاذ", "اخي", "اختي", "جدا", "كثيرا"]) {
    rest = rest.split(` ${filler} `).join(" ")
  }
  return rest.trim().length === 0
}

/**
 * تُصنّف رسالة المستخدم. الترتيب مقصود:
 *   1) التطبيع.
 *   2) تجاوز المحتوى (Content override) أولاً → داخل النطاق فوراً.
 *   3) تحويل هجري (شهر هجري + سنة/عبارة تحويل).
 *   4) توقيت مناسبة (أداة استفهام زمنية + اسم مناسبة).
 *   5) الافتراضي المحافظ: داخل النطاق.
 */
export function classifyScope(userMessage: string): ScopeResult {
  // مدخل فارغ/غير نصّي → داخل النطاق (محافظ).
  if (!userMessage || typeof userMessage !== "string") {
    return { inScope: true }
  }

  const norm = normalizeArabic(userMessage)
  if (!norm) {
    return { inScope: true }
  }

  // (2) تجاوز المحتوى — يُفحص أولاً: أي اسم محتوى يعني أن السؤال عن محتوى
  // العتبة (لا عن تاريخ/توقيت) فيبقى داخل النطاق حتى مع وجود اسم مناسبة.
  for (const noun of CONTENT_NOUNS) {
    if (hasPhrase(norm, noun)) {
      return { inScope: true }
    }
  }

  // (3) تحويل التواريخ الهجرية: يتطلب اسم شهر هجري + (سنة هجرية أو عبارة تحويل).
  const hasHijriMonth = HIJRI_MONTHS.some((m) => hasPhrase(norm, m))
  if (hasHijriMonth) {
    const hasHijriYear = HIJRI_YEAR_REGEX.test(norm)
    const hasConversionPhrase = CONVERSION_PHRASES.some((p) => hasPhrase(norm, p))
    if (hasHijriYear || hasConversionPhrase) {
      return {
        inScope: false,
        category: "hijri_conversion",
        reason:
          "طلب تحويل تاريخ هجري (اسم شهر هجري مقرون بسنة هجرية أو عبارة تحويل) — خارج نطاق مساعد العتبة.",
      }
    }
  }

  // (4) توقيت المناسبات الدينية: أداة استفهام زمنية + اسم مناسبة.
  const hasTimeInterrogative = TIME_INTERROGATIVES.some((t) => hasPhrase(norm, t))
  if (hasTimeInterrogative) {
    const hasOccasion = OCCASIONS.some((o) => hasPhrase(norm, o))
    if (hasOccasion) {
      return {
        inScope: false,
        category: "occasion_timing",
        reason:
          "سؤال عن توقيت مناسبة دينية (أداة استفهام زمنية مقرونة باسم مناسبة) — يُوجَّه للتقويم لا لمعرفة عامة.",
      }
    }
  }

  // (5) الافتراضي المحافظ: عند عدم وجود مطابقة واضحة نبقى داخل النطاق.
  // لا نحاول كشف «المعلومات العامة» حتمياً (فضفاض جداً) — يُترك لشبكة الأمان
  // tool_choice:"auto" والموجّه.
  return { inScope: true }
}
