/**
 * تطبيع النص العربي: توحيد الهمزات والألف والتاء المربوطة
 */
export function normalizeArabic(text: string): string {
  return text
    .replace(/[أإآا]/g, "ا")
    .replace(/[ةه]/g, "ه")
    .replace(/[يى]/g, "ي")
    .replace(/و\b/g, "ي")   // توحيد أبو/أبي
    .replace(/فاضل/g, "فضل") // توحيد فاضل/فضل
    .replace(/\s+/g, " ")
    .trim()
    .toLowerCase()
}

/**
 * البحث في FAQ — يعيد الإجابة إذا تطابق أحد الأنماط مع سؤال المستخدم
 */
export function searchFAQ(query: string): FAQEntry | null {
  const q = normalizeArabic(query)
  if (!q || q.length < 5) return null  // تجاهل الرسائل القصيرة جداً (أقل من 5 أحرف)

  for (const entry of FAQ_ENTRIES) {
    for (const pattern of entry.patterns) {
      const p = normalizeArabic(pattern)
      // التطابق يجب أن يكون كلمة مستقلة (word boundary) وليس جزءاً من كلمة أخرى
      const regex = new RegExp(`(^|\\s)${p.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}($|\\s)`)
      if (regex.test(q)) {
        return entry
      }
    }
  }
  return null
}
