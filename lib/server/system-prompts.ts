/**
 * يبني سطر «تاريخ اليوم» بتوقيت بغداد (لا بتوقيت الخادم — Vercel يعمل بـ UTC).
 *
 * ⚠️ كان الموجّه يحمل «السنة الحالية = 2026» مثبّتة نصّاً، فكان البوت سيبحث في
 * سنة خاطئة لكل سؤال زمني ابتداءً من 2027. الحقن الديناميكي يزيل هذا الصنف من
 * الأعطال بالكامل (معرفة مجمّدة في الشيفرة).
 */
function todayLine(now: Date = new Date()): string {
  const tz = "Asia/Baghdad"
  const y = new Intl.DateTimeFormat("en-CA", { timeZone: tz, year: "numeric" }).format(now)
  const full = new Intl.DateTimeFormat("ar-IQ", {
    timeZone: tz,
    weekday: "long",
    year: "numeric",
    month: "long",
    day: "numeric",
  }).format(now)
  const iso = new Intl.DateTimeFormat("en-CA", {
    timeZone: tz,
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
  }).format(now)
  return `تاريخ اليوم: ${full} (${iso}) — السنة الحالية = ${y}`
}

/**
 * موجّه **اختيار الأداة** — الجوهري وحده (بلا قواعد العرض).
 *
 * يُستعمل في نداءات resolveToolCalls التي تتكرّر حتى 3 مرات وتحمل تعريفات
 * الأدوات أيضاً. قواعد العرض لا تؤثر على اختيار الأداة ولا على صياغة الاستعلام
 * من اللهجة، والجواب النهائي يُولَّد دائماً في النداء المتدفّق بالموجّه الكامل.
 *
 * ملاحظة تخزين مؤقّت: هذا النصّ **بادئة** حرفية للموجّه الكامل، فيتشارك النداءان
 * نفس البادئة المخزّنة.
 */
export function getToolSelectionPrompt(): string {
  return SITE_BOT_CORE_PROMPT.replace("{{TODAY}}", todayLine())
}

export function getSiteSystemPrompt(
  customInstructions?: string
): string {
  let prompt = SITE_BOT_SYSTEM_PROMPT.replace("{{TODAY}}", todayLine())

  if (customInstructions) {
    prompt += `\n\n## تعليمات إضافية خاصة بهذه الجلسة:\n${customInstructions}`
  }

  return prompt
}

/**
 * دالة للحصول على رد fallback حسب الحالة
 */
export function getFallbackResponse(
  type: "no_results" | "api_error" | "out_of_scope"
): string {
  switch (type) {
    case "no_results":
      return FALLBACK_NO_RESULTS
    case "api_error":
      return FALLBACK_API_ERROR
    case "out_of_scope":
      return FALLBACK_OUT_OF_SCOPE
    default:
      return FALLBACK_NO_RESULTS
  }
}
